"""Offline build for the independent stock-1770 camera migration candidate.

Uses the installed JDK/Android SDK and compile-only Xposed declarations. Signing
passwords are supplied through AURORA_LSP_KS_PASS and AURORA_LSP_KEY_PASS; they are
passed to apksigner through its env: interface and never written to build logs.
The default keystore is the existing private project signing entry. No key is
copied into this project or its source archive.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import uuid
import zipfile


ROOT = Path(__file__).resolve().parent
JAVA = Path("D:/DevTools/jdks/jdk-21.0.12.1+1/bin")
BT = Path("D:/DevTools/AndroidSdk/build-tools/37.0.0")
SDK = Path("D:/DevTools/AndroidSdk/platforms/android-37.0/android.jar")
DEFAULT_KEYSTORE = Path("D:/cam18pm/m3-port/m3-v16-probe-debug.jks")
PACKAGE = "com.aurora.camera.compat"
ENTRY = PACKAGE + ".CompatModule"
VERSION = "0.1.125"
VERSION_CODE = 10225
STOCK_SHA256 = "e25b1ed5581baddd4e1d7f1ae60c1e0f1b1251645df5ba90dfbb9c42953b4a07"


def sha256(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def run(arguments: list[object], work: Path, name: str) -> str:
    env = os.environ.copy()
    env["JAVA_HOME"] = str(JAVA.parent)
    temporary = work / "tmp"
    temporary.mkdir(exist_ok=True)
    for variable in ("TEMP", "TMP", "TMPDIR"):
        env[variable] = str(temporary)
    env["JAVA_TOOL_OPTIONS"] = env.get("JAVA_TOOL_OPTIONS", "") + " -Djava.io.tmpdir=" + str(temporary)
    result = subprocess.run(
        [str(argument) for argument in arguments], capture_output=True, env=env
    )
    (work / (name + ".stdout.bin")).write_bytes(result.stdout)
    (work / (name + ".stderr.bin")).write_bytes(result.stderr)
    output = result.stdout.decode("utf-8", "replace") + result.stderr.decode(
        "utf-8", "replace"
    )
    (work / (name + ".log")).write_text(output, encoding="utf-8")
    if result.returncode:
        raise RuntimeError(f"{name} exit {result.returncode}; see {work / (name + '.log')}")
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--unsigned", action="store_true", help="build an explicitly unsigned development APK"
    )
    parser.add_argument("--output-name", help="unique APK filename under release/; existing files are never replaced")
    args = parser.parse_args()

    source_paths = sorted((ROOT / "src").rglob("*.java"))
    stub_paths = sorted((ROOT / "api-stubs").rglob("*.java"))
    asset_paths = sorted(path for path in (ROOT / "assets").rglob("*") if path.is_file())
    native_paths = sorted((ROOT / "native/auth239").glob("*.so")) + sorted((ROOT / "native/editor291").glob("*.so"))
    native_producer_paths = [ROOT / name for name in (
        "native/auth250-preview/build.py", "native/auth250-preview/loader.c",
        "native/auth250-preview/input/libMiFilterSDK.so", "native/editor291/environment.c", "native/editor291/build.py")]
    if any(path.relative_to(ROOT / "assets").as_posix() == "xposed_init" for path in asset_paths):
        raise RuntimeError("assets/xposed_init is generated by the builder; source asset name conflicts")
    if not source_paths or not stub_paths:
        raise RuntimeError("module sources or compile-only Xposed declarations are missing")
    if not (ROOT / "src/com/aurora/camera/compat/FeatureRegistry.java").is_file():
        raise RuntimeError("FeatureRegistry.java is not ready; no build started")
    tools = [JAVA / "javac.exe", JAVA / "jar.exe", BT / "d8.bat", BT / "aapt.exe",
             BT / "zipalign.exe", BT / "apksigner.bat", SDK]
    for tool in tools:
        if not tool.is_file():
            raise FileNotFoundError(tool)

    keystore = Path(os.environ.get("AURORA_LSP_KEYSTORE", str(DEFAULT_KEYSTORE)))
    alias = os.environ.get("AURORA_LSP_KEY_ALIAS", "m3probe")
    if not args.unsigned:
        if not keystore.is_file():
            raise FileNotFoundError("existing private signing keystore is unavailable")
        for variable in ("AURORA_LSP_KS_PASS", "AURORA_LSP_KEY_PASS"):
            if not os.environ.get(variable):
                raise RuntimeError(f"required private signing environment variable is missing: {variable}")

    suffix = "-unsigned" if args.unsigned else ""
    output_name = args.output_name or f"CameraCompat-{VERSION}{suffix}.apk"
    if Path(output_name).name != output_name or Path(output_name).suffix.lower() != ".apk":
        raise ValueError("--output-name must be an APK filename, without directories")
    output = ROOT / "release" / output_name
    if output.exists() or output.with_suffix(".json").exists():
        raise FileExistsError(f"candidate already exists; refusing overwrite: {output}")
    work = ROOT / "build" / ("lsp-" + uuid.uuid4().hex[:12])
    for directory in (work / "classes", work / "dex", work / "package/res/values",
                      work / "package/assets", output.parent):
        directory.mkdir(parents=True, exist_ok=True)

    # Other feature authors can still edit the live tree. Compile and package only
    # these captured bytes, and never report later source hashes as build inputs.
    captured_inputs = {
        path.relative_to(ROOT).as_posix(): path.read_bytes()
        for path in source_paths + stub_paths + asset_paths + native_paths + native_producer_paths + sorted((ROOT / "port-smali").rglob("*.smali")) + sorted(p for p in (ROOT / "res").rglob("*") if p.is_file()) + [ROOT / "tools/AssembleWatermark.java"]
    }
    input_hashes = {name: hashlib.sha256(data).hexdigest() for name, data in captured_inputs.items()}
    builder_hash = sha256(Path(__file__).resolve())
    snapshot = work / "input_snapshot"
    for name, data in captured_inputs.items():
        captured_path = snapshot / name
        captured_path.parent.mkdir(parents=True, exist_ok=True)
        captured_path.write_bytes(data)
    (work / "INPUT_SNAPSHOT.json").write_text(
        json.dumps({"snapshot": str(snapshot), "files": input_hashes}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    source_paths = [snapshot / name for name in input_hashes if name.startswith("src/")]
    stub_paths = [snapshot / name for name in input_hashes if name.startswith("api-stubs/")]
    asset_paths = [snapshot / name for name in input_hashes if name.startswith("assets/")]
    asset_root = snapshot / "assets"

    tree = work / "package"
    for name in input_hashes:
        if name.startswith("res/"):
            target = tree / name
            target.parent.mkdir(parents=True,exist_ok=True)
            target.write_bytes((snapshot / name).read_bytes())
    manifest = f'''<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    package="{PACKAGE}" android:versionCode="{VERSION_CODE}" android:versionName="{VERSION}">
    <uses-sdk android:minSdkVersion="31" android:targetSdkVersion="35"/>
    <queries>
        <package android:name="com.android.camera"/>
        <package android:name="com.miui.mediaeditor"/>
    </queries>
    <application android:label="6.8Cam原包适配" android:allowBackup="false" android:hasCode="true">
        <meta-data android:name="xposedmodule" android:value="true"/>
        <meta-data android:name="xposeddescription" android:value="Aurora 1770原包适配与滤镜管理"/>
        <meta-data android:name="xposedminversion" android:value="93"/>
        <meta-data android:name="xposedscope" android:resource="@array/xposed_scope"/>
        <provider android:name=".sharedlut.LutShare246Provider"
            android:authorities="com.aurora.camera.compat.lutshare246"
            android:process=":lutshare" android:exported="true"
            android:grantUriPermissions="false"/>
        <receiver android:name=".sharedlut.LutShare257Receiver"
            android:process=":lutshare" android:exported="true"/>
    </application>
</manifest>
'''
    (tree / "AndroidManifest.xml").write_text(manifest, encoding="utf-8")
    (tree / "res/values/arrays.xml").write_text(
        '<resources><string-array name="xposed_scope"><item>com.android.camera</item><item>com.miui.mediaeditor</item>'
        '</string-array></resources>\n', encoding="utf-8"
    )
    (tree / "assets/xposed_init").write_text(ENTRY + "\n", encoding="utf-8")

    run([JAVA / "javac.exe", "--release", "8", "-encoding", "UTF-8", "-cp", SDK,
         "-d", work / "classes", *source_paths, *stub_paths], work, "javac")
    # Only com/ is packaged. de/robv/android/xposed remains compile-only.
    run([JAVA / "jar.exe", "cf", work / "module.jar", "-C", work / "classes", "com"], work, "jar")
    with zipfile.ZipFile(work / "module.jar") as module_jar:
        if any(name.startswith("de/robv/android/xposed/") for name in module_jar.namelist()):
            raise RuntimeError("compile-only Xposed declarations leaked into module.jar")
    apktool = Path("D:/DevTools/apktool/apktool.jar")
    run([JAVA / "javac.exe", "-encoding", "UTF-8", "-cp", apktool, "-d", work / "assembler", snapshot / "tools/AssembleWatermark.java"], work, "assembler-compile")
    run([JAVA / "java.exe", "-cp", str(work / "assembler") + ";" + str(apktool), "AssembleWatermark", snapshot / "port-smali", work / "watermark-helpers.dex"], work, "assembler")
    run([BT / "d8.bat", "--min-api", "31", "--lib", SDK, "--output", work / "dex",
         work / "module.jar", work / "watermark-helpers.dex"], work, "d8")
    run([BT / "aapt.exe", "package", "-f", "-M", tree / "AndroidManifest.xml",
         "-S", tree / "res", "-I", SDK, "-F", work / "resources.apk"], work, "aapt")

    with zipfile.ZipFile(work / "resources.apk") as resources, zipfile.ZipFile(
        work / "unsigned.apk", "w"
    ) as apk:
        for entry in resources.infolist():
            apk.writestr(entry, resources.read(entry.filename))
        apk.write(tree / "assets/xposed_init", "assets/xposed_init")
        for dex in sorted((work / "dex").glob("classes*.dex")):
            apk.write(dex, dex.name)
        packaged_names = set(apk.namelist())
        for source_asset in asset_paths:
            archive_name = "assets/" + source_asset.relative_to(asset_root).as_posix()
            if archive_name in packaged_names:
                raise RuntimeError(f"source asset conflicts with generated APK entry: {archive_name}")
            apk.write(source_asset, archive_name)
            packaged_names.add(archive_name)
        for source_native in native_paths:
            name=source_native.relative_to(ROOT).as_posix()
            info=zipfile.ZipInfo("lib/arm64-v8a/"+source_native.name)
            info.compress_type=zipfile.ZIP_STORED
            apk.writestr(info,(snapshot/name).read_bytes())
    run([BT / "zipalign.exe", "-P", "16", "-f", "4", work / "unsigned.apk",
         work / "aligned.apk"], work, "align")

    if args.unsigned:
        with (work / "aligned.apk").open("rb") as source, output.open("xb") as target:
            while block := source.read(1024 * 1024):
                target.write(block)
    else:
        run([BT / "apksigner.bat", "sign", "--ks", keystore, "--ks-key-alias", alias,
             "--ks-pass", "env:AURORA_LSP_KS_PASS", "--key-pass", "env:AURORA_LSP_KEY_PASS",
             "--out", output, work / "aligned.apk"], work, "sign")
        run([BT / "apksigner.bat", "verify", "--verbose", "--print-certs", output], work, "signature")
    run([BT / "zipalign.exe", "-c", "-P", "16", "4", output], work, "alignment")
    badging = run([BT / "aapt.exe", "dump", "badging", output], work, "badging")
    identity = f"package: name='{PACKAGE}' versionCode='{VERSION_CODE}' versionName='{VERSION}'"
    if identity not in badging:
        raise RuntimeError("candidate package/version metadata differs from declared identity")
    with zipfile.ZipFile(output) as apk:
        if apk.testzip() is not None or len(apk.namelist()) != len(set(apk.namelist())):
            raise RuntimeError("candidate ZIP integrity check failed")
        if apk.read("assets/xposed_init").decode("utf-8").strip() != ENTRY:
            raise RuntimeError("candidate Xposed entry differs from declared identity")
        for source_asset in asset_paths:
            archive_name = "assets/" + source_asset.relative_to(asset_root).as_posix()
            if hashlib.sha256(apk.read(archive_name)).hexdigest() != sha256(source_asset):
                raise RuntimeError(f"candidate asset differs from source: {archive_name}")

    current_input_paths = {path.relative_to(ROOT).as_posix(): path
                           for folder in ("src", "api-stubs", "assets", "port-smali", "res", "tools", "native/auth239", "native/editor291")
                           for path in (ROOT / folder).rglob("*") if path.is_file() and (folder != "tools" or path.name == "AssembleWatermark.java")}
    current_input_paths.update({path.relative_to(ROOT).as_posix(): path for path in native_producer_paths})
    changed_since_snapshot = sorted(
        name for name in set(input_hashes) | set(current_input_paths)
        if name not in input_hashes or name not in current_input_paths
        or sha256(current_input_paths[name]) != input_hashes[name]
    )
    report = {
        "artifact": str(output), "sha256": sha256(output), "bytes": output.stat().st_size,
        "package": PACKAGE, "version": VERSION, "version_code": VERSION_CODE,
        "target_stock_apk_sha256": STOCK_SHA256, "target_device": "aurora",
        "scope": ["com.android.camera", "com.miui.mediaeditor"], "work": str(work),
        "signature_verified": not args.unsigned, "alignment_16kb_verified": True,
        "zip_integrity_verified": True, "installed": False, "runtime_verified": False,
        "full_migration_verified": False,
        "source_files": {name: digest for name, digest in input_hashes.items()
                         if name.startswith(("src/", "api-stubs/"))},
        "asset_files": {name: digest for name, digest in input_hashes.items() if name.startswith("assets/")},
        "input_snapshot": str(snapshot), "source_snapshot_stale": bool(changed_since_snapshot),
        "source_snapshot_changes": changed_since_snapshot,
        "build_script_sha256": builder_hash,
        "extra_input_files": {name:digest for name,digest in input_hashes.items() if name.startswith(("port-smali/","res/","tools/","native/auth239/","native/auth250-preview/","native/editor291/"))},
    }
    (work / "BUILD_RESULT.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    output.with_suffix(".json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
